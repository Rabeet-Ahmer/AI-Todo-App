# Shared settings with Better Auth
# Prefer explicit JWT_SECRET_KEY but gracefully fall back to BETTER_AUTH_SECRET
SECRET_KEY = os.getenv("JWT_SECRET_KEY") or os.getenv("BETTER_AUTH_SECRET")
ALGORITHM = os.getenv("JWT_ALGORITHM", "HS256")
BETTER_AUTH_URL = os.getenv("BETTER_AUTH_URL", "http://localhost:3000")

security = HTTPBearer()


async def verify_token(credentials: HTTPAuthorizationCredentials = Depends(security)) -> dict:
    """
    Verify the JWT token generated by Better Auth.
    """
    if not credentials:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Missing authentication credentials",
            headers={"WWW-Authenticate": "Bearer"},
        )

    if not SECRET_KEY:
        # Misconfiguration: backend cannot validate tokens without a secret
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="JWT secret key is not configured on the backend",
        )

    token = credentials.credentials

    try:
        # Decode JWT signature using SHARED secret
        payload = jwt.decode(
            token,
            SECRET_KEY,
            algorithms=[ALGORITHM],
            options={"verify_aud": False}  # Better Auth aud might vary
        )
        return payload
    except JWTError as e:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail=f"Invalid token: {str(e)}",
            headers={"WWW-Authenticate": "Bearer"},
        )


def extract_user_id_from_token(token: str) -> str:
    """
    Extract user_id from JWT token.

    Args:
        token: JWT token string

    Returns:
        user_id (string) from JWT sub claim

    Raises:
        JWTError: If token is invalid or user_id not found
    """
    if not SECRET_KEY:
        raise ValueError("JWT secret key is not configured")

    try:
        payload = jwt.decode(
            token,
            SECRET_KEY,
            algorithms=[ALGORITHM],
            options={"verify_aud": False}
        )

        # Extract user_id from 'sub' claim
        user_id = payload.get("sub")
        if not user_id:
            raise JWTError("Token missing subject claim")

        return str(user_id)  # Better Auth uses string UUIDs

    except JWTError:
        raise
